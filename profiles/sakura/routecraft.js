// biome-ignore lint/correctness/noUnusedVariables: Clash Verge invokes this global entrypoint.
function main(config) {
  if (!config || !Array.isArray(config.proxies)) return config;
  const nodes = config.proxies.filter(
    (p) => p?.server && p.type && typeof p.name === 'string' && !/剩余|到期|重置/.test(p.name),
  );
  if (!nodes.length) return config;
  const definitions = [
    ['香港', /香港|Hong.?Kong|🇭🇰/i],
    ['新加坡', /新加坡|Singapore|🇸🇬/i],
    ['台湾', /台湾|Taiwan|🇹🇼/i],
    ['日本', /日本|Japan|🇯🇵/i],
    ['美国', /美国|United.?States|🇺🇸/i],
  ];
  const regions = [];
  const assigned = new Set();
  for (const [name, re] of definitions) {
    const members = nodes.filter((p) => re.test(p.name)).map((p) => p.name);
    if (members.length) {
      members.forEach((n) => {
        assigned.add(n);
      });
      regions.push({
        name,
        type: 'url-test',
        proxies: members,
        url: 'https://www.gstatic.com/generate_204',
        interval: 600,
        tolerance: 80,
        lazy: true,
      });
    }
  }
  const other = nodes.map((p) => p.name).filter((n) => !assigned.has(n));
  if (other.length) regions.push({ name: '其他地区', type: 'select', proxies: other });
  const names = regions.map((g) => g.name);
  const select = (name, options) => ({ name, type: 'select', proxies: [...new Set(options)] });
  const preferred = ['美国', '新加坡', '日本'].filter((n) => names.includes(n));
  config['proxy-groups'] = [
    select('Proxy', [...names, ...nodes.map((p) => p.name)]),
    select('CDN', ['DIRECT', 'Proxy', ...names]),
    select('Storage', ['Proxy', 'DIRECT', ...names]),
    select('AI', [...preferred, 'Proxy', ...names]),
    select('download', ['DIRECT', 'Proxy', ...names]),
    select('domestic', ['DIRECT', 'Proxy', ...names]),
    select('social media', ['Proxy', ...names, 'DIRECT']),
    select('xjtlu', ['DIRECT', 'Proxy', ...names]),
    ...regions,
  ];
  config['rule-providers'] = JSON.parse(JSON.stringify(PROVIDERS));
  config.rules = [...RULES];
  const icons = {
    Proxy: '🚀 Proxy',
    CDN: '🚄 CDN',
    Storage: '🗄️ Storage',
    AI: '🤖 AI',
    download: '⬇️ download',
    domestic: '🇨🇳 domestic',
    'social media': '📱 social media',
    xjtlu: '🏫 xjtlu',
    香港: '🇭🇰 香港',
    新加坡: '🇸🇬 新加坡',
    台湾: '🇹🇼 台湾',
    日本: '🇯🇵 日本',
    美国: '🇺🇸 美国',
    其他地区: '🌍 其他地区',
  };
  for (const group of config['proxy-groups']) {
    group.name = icons[group.name] || group.name;
    group.proxies = group.proxies.map((name) => icons[name] || name);
  }
  config.rules = config.rules.map((rule) => {
    const parts = rule.split(',');
    const target = parts[0] === 'MATCH' ? 1 : 2;
    parts[target] = icons[parts[target]] || parts[target];
    return parts.join(',');
  });
  config.mode = 'rule';
  return config;
}
